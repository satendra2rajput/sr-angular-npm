import { JsonLdData, JsonLdGraph, SeoJsonLd } from '../models/json-ld';
import { SCHEMA_ORG_CONTEXT } from '../constants/seo.constants';

/**
 * Checks whether the supplied value is a valid JSON-LD object.
 */
export function isJsonLdData(value: unknown): value is JsonLdData {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

/**
 * Checks whether the supplied value is a JSON-LD graph.
 */
export function isJsonLdGraph(value: unknown): value is JsonLdGraph {
  return isJsonLdData(value) && Array.isArray((value as JsonLdGraph)['@graph']);
}

/**
 * Normalizes JSON-LD input into an array.
 *
 * This allows the service to work consistently with:
 *
 * - Single schema
 * - Multiple schemas
 * - @graph
 */
export function normalizeJsonLd(data: SeoJsonLd): JsonLdData[] {
  if (Array.isArray(data)) {
    return data;
  }

  if (isJsonLdGraph(data)) {
    return [
      {
        ...data,
      },
    ];
  }

  return [data];
}

/**
 * Adds the default Schema.org context
 * when it has not been provided.
 */
export function normalizeJsonLdContext(data: JsonLdData): JsonLdData {
  if (data['@context']) {
    return data;
  }

  return {
    '@context': SCHEMA_ORG_CONTEXT,
    ...data,
  };
}

/**
 * Serializes JSON-LD safely for insertion
 * into a script element.
 */
export function serializeJsonLd(data: JsonLdData | JsonLdData[]): string {
  const normalized = Array.isArray(data)
    ? data.map(normalizeJsonLdContext)
    : normalizeJsonLdContext(data);

  return JSON.stringify(normalized);
}

/**
 * Finds all JSON-LD script elements created
 * for SEO.
 */
export function getJsonLdScripts(document: Document): HTMLScriptElement[] {
  return Array.from(
    document.querySelectorAll('script[type="application/ld+json"][data-kudo-seo="true"]'),
  );
}

/**
 * Removes all JSON-LD scripts created by
 * @kudoengineer/seo.
 */
export function removeJsonLd(document: Document): void {
  const scripts = getJsonLdScripts(document);

  scripts.forEach((script) => {
    script.remove();
  });
}

/**
 * Creates a JSON-LD script element.
 */
export function createJsonLdScript(
  document: Document,
  data: JsonLdData | JsonLdData[],
): HTMLScriptElement {
  const script = document.createElement('script');

  script.type = 'application/ld+json';

  script.setAttribute('data-kudo-seo', 'true');

  script.textContent = serializeJsonLd(data);

  return script;
}

/**
 * Updates the document with JSON-LD structured data.
 *
 * Existing JSON-LD generated by this package
 * is removed before inserting the new schema.
 */
export function updateJsonLd(document: Document, data: SeoJsonLd | undefined | null): void {
  if (!data) {
    removeJsonLd(document);
    return;
  }

  removeJsonLd(document);

  const normalized = normalizeJsonLd(data);

  const scripts = normalized.map((schema) => createJsonLdScript(document, schema));

  scripts.forEach((script) => {
    document.head.appendChild(script);
  });
}
