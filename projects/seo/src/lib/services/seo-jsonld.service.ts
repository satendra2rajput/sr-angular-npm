import { DOCUMENT } from '@angular/common';
import { Inject, Injectable } from '@angular/core';

import { JsonLdData, SeoJsonLd } from '../models/json-ld';
import { removeJsonLd, updateJsonLd } from '../utils/json-ld.util';

@Injectable({
  providedIn: 'root',
})
export class SeoJsonLdService {
  constructor(
    @Inject(DOCUMENT)
    private readonly document: Document,
  ) {}

  /**
   * Sets a single JSON-LD schema.
   *
   * Example:
   *
   * {
   *   "@context": "https://schema.org",
   *   "@type": "Article",
   *   "headline": "Angular Roadmap"
   * }
   */
  set(data: JsonLdData): void {
    updateJsonLd(this.document, data);
  }

  /**
   * Sets one or multiple JSON-LD schemas.
   */
  setMany(data: SeoJsonLd): void {
    updateJsonLd(this.document, data);
  }

  /**
   * Removes JSON-LD generated by
   * @kudoengineer/seo.
   */
  reset(): void {
    removeJsonLd(this.document);
  }
}
