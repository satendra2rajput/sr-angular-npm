import { DOCUMENT } from '@angular/common';
import { Inject, Injectable } from '@angular/core';

import { getCanonicalUrl, removeCanonicalLink, updateCanonicalLink } from '../utils/canonical.util';

@Injectable({
  providedIn: 'root',
})
export class SeoCanonicalService {
  constructor(
    @Inject(DOCUMENT)
    private readonly document: Document,
  ) {}

  /**
   * Creates or updates the canonical URL.
   *
   * Example:
   *
   * <link
   *   rel="canonical"
   *   href="https://kudoengineer.com/angular"
   * >
   */
  set(url?: string): void {
    if (!url?.trim()) {
      return;
    }

    updateCanonicalLink(this.document, url);
  }

  /**
   * Returns the current canonical URL.
   */
  get(): string | null {
    return getCanonicalUrl(this.document);
  }

  /**
   * Removes the canonical link
   * generated by the SEO package.
   */
  reset(): void {
    removeCanonicalLink(this.document);
  }
}
