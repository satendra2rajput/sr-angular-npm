import { DOCUMENT } from '@angular/common';
import { Inject, Injectable } from '@angular/core';

import { SeoConfig } from '../models/seo-config';
import { JsonLdData, SeoJsonLd } from '../models/json-ld';

import { SeoMetaService } from './seo-meta.service';
import { SeoCanonicalService } from './seo-canonical.service';
import { SeoOgService } from './seo-og.service';
import { SeoTwitterService } from './seo-twitter.service';
import { SeoJsonLdService } from './seo-jsonld.service';

@Injectable({
  providedIn: 'root',
})
export class SeoService {
  constructor(
    private readonly seoMeta: SeoMetaService,
    private readonly seoCanonical: SeoCanonicalService,
    private readonly seoOg: SeoOgService,
    private readonly seoTwitter: SeoTwitterService,
    private readonly seoJsonLd: SeoJsonLdService,

    @Inject(DOCUMENT)
    private readonly document: Document,
  ) {}

  /**
   * Applies complete SEO configuration.
   *
   * This is the main method consumers
   * should use in most cases.
   */
  set(config: SeoConfig): void {
    if (!config) {
      return;
    }

    this.seoMeta.set(config);

    this.seoMeta.setLanguage(this.document, config.language);

    this.seoCanonical.set(config.canonical);

    this.seoOg.set(config.og);

    this.seoTwitter.set(config.twitter);

    if (config.jsonLd) {
      this.seoJsonLd.setMany(config.jsonLd);
    } else if (config.resetMissing) {
      this.seoJsonLd.reset();
    }
  }

  /**
   * Updates only the page title.
   */
  setTitle(title: string): void {
    this.seoMeta.setTitle(title);
  }

  /**
   * Updates only the meta description.
   */
  setDescription(description: string): void {
    this.seoMeta.setDescription(description);
  }

  /**
   * Updates keywords.
   */
  setKeywords(keywords: string[]): void {
    this.seoMeta.setKeywords(keywords);
  }

  /**
   * Updates robots meta.
   */
  setRobots(robots: string): void {
    this.seoMeta.setRobots(robots);
  }

  /**
   * Updates author meta.
   */
  setAuthor(author: string): void {
    this.seoMeta.setAuthor(author);
  }

  /**
   * Updates theme color.
   */
  setThemeColor(color: string): void {
    this.seoMeta.setThemeColor(color);
  }

  /**
   * Updates document language.
   */
  setLanguage(language: string): void {
    this.seoMeta.setLanguage(this.document, language);
  }

  /**
   * Updates canonical URL.
   */
  setCanonical(url: string): void {
    this.seoCanonical.set(url);
  }

  /**
   * Returns current canonical URL.
   */
  getCanonical(): string | null {
    return this.seoCanonical.get();
  }

  /**
   * Updates Open Graph metadata.
   */
  setOpenGraph(config: SeoConfig['og']): void {
    this.seoOg.set(config);
  }

  /**
   * Updates Twitter/X metadata.
   */
  setTwitter(config: SeoConfig['twitter']): void {
    this.seoTwitter.set(config);
  }

  /**
   * Updates a single JSON-LD schema.
   */
  setJsonLd(data: JsonLdData): void {
    this.seoJsonLd.set(data);
  }

  /**
   * Updates one or multiple JSON-LD schemas.
   */
  setJsonLdMany(data: SeoJsonLd): void {
    this.seoJsonLd.setMany(data);
  }

  /**
   * Resets SEO metadata generated by
   * this package.
   *
   * This removes:
   *
   * - Title
   * - Description
   * - Keywords
   * - Robots
   * - Author
   * - Theme color
   * - Canonical
   * - Open Graph
   * - Twitter/X
   * - JSON-LD
   */
  reset(): void {
    this.seoMeta.reset();
    this.seoCanonical.reset();
    this.seoOg.reset();
    this.seoTwitter.reset();
    this.seoJsonLd.reset();

    this.document.documentElement.lang = '';
  }
}
