import { Injectable } from '@angular/core';
import { Meta } from '@angular/platform-browser';

import { META_NAMES } from '../constants/meta.constants';
import { SeoTwitter } from '../models/seo-config';
import { removeMetaTag, updateMetaTag } from '../utils/meta.util';

@Injectable({
  providedIn: 'root',
})
export class SeoTwitterService {
  constructor(private readonly meta: Meta) {}

  /**
   * Sets Twitter/X card type.
   *
   * Example:
   * summary
   * summary_large_image
   */
  setCard(value?: 'summary' | 'summary_large_image'): void {
    this.setMeta(META_NAMES.TWITTER_CARD, value);
  }

  /**
   * Sets Twitter/X title.
   */
  setTitle(value?: string): void {
    this.setMeta(META_NAMES.TWITTER_TITLE, value);
  }

  /**
   * Sets Twitter/X description.
   */
  setDescription(value?: string): void {
    this.setMeta(META_NAMES.TWITTER_DESCRIPTION, value);
  }

  /**
   * Sets Twitter/X image.
   */
  setImage(value?: string): void {
    this.setMeta(META_NAMES.TWITTER_IMAGE, value);
  }

  /**
   * Sets Twitter/X site username.
   *
   * Example:
   * @kudoengineer
   */
  setSite(value?: string): void {
    this.setMeta(META_NAMES.TWITTER_SITE, value);
  }

  /**
   * Sets Twitter/X creator username.
   *
   * Example:
   * @satendra
   */
  setCreator(value?: string): void {
    this.setMeta(META_NAMES.TWITTER_CREATOR, value);
  }

  /**
   * Applies complete Twitter/X configuration.
   */
  set(config?: SeoTwitter): void {
    if (!config) {
      return;
    }

    this.setCard(config.card);
    this.setTitle(config.title);
    this.setDescription(config.description);
    this.setImage(config.image);
    this.setSite(config.site);
    this.setCreator(config.creator);
  }

  /**
   * Removes all Twitter/X metadata
   * generated by the SEO service.
   */
  reset(): void {
    removeMetaTag(this.meta, META_NAMES.TWITTER_CARD);

    removeMetaTag(this.meta, META_NAMES.TWITTER_TITLE);

    removeMetaTag(this.meta, META_NAMES.TWITTER_DESCRIPTION);

    removeMetaTag(this.meta, META_NAMES.TWITTER_IMAGE);

    removeMetaTag(this.meta, META_NAMES.TWITTER_SITE);

    removeMetaTag(this.meta, META_NAMES.TWITTER_CREATOR);
  }

  /**
   * Internal helper for Twitter/X meta tags.
   */
  private setMeta(name: string, content?: string): void {
    if (!content?.trim()) {
      return;
    }

    updateMetaTag(this.meta, name, content);
  }
}
